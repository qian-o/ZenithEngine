namespace ZenithEngine.Common.Enums;

public enum GamepadAxis
{
    /// <summary>
    /// The unknown gamepad axis.
    /// </summary>
    Unknown,

    /// <summary>
    /// The left stick X-axis.
    /// </summary>
    LeftX,

    /// <summary>
    /// The left stick Y-axis.
    /// </summary>
    LeftY,

    /// <summary>
    /// The right stick X-axis.
    /// </summary>
    RightX,

    /// <summary>
    /// The right stick Y-axis.
    /// </summary>
    RightY,

    /// <summary>
    /// The left trigger axis.
    /// </summary>
    TriggerLeft,

    /// <summary>
    /// The right trigger axis.
    /// </summary>
    TriggerRight
}